# خواندن فایل
df = pd.read_excel("Yazd Consumption.xlsx")

# پاک‌سازی نام ستون‌ها
df = df.rename(columns=lambda x: x.strip())

# تعیین ستون‌های ساعتی
hour_cols = [f'H{i}' for i in range(1, 25)]

# ------------------ حذف ردیف‌هایی که همه مقادیرشان منفی است ------------------
df = df[~(df[hour_cols] < 0).all(axis=1)].copy()

# ------------------ جایگزینی مقادیر منفی با میانگین سایر ساعات همان ردیف ------------------
def replace_negatives(row):
    for h in hour_cols:
        if row[h] < 0:
            non_negative_vals = [row[col] for col in hour_cols if row[col] >= 0]
            mean_val = sum(non_negative_vals) / len(non_negative_vals) if non_negative_vals else 0
            row[h] = mean_val
    return row

df = df.apply(replace_negatives, axis=1)

# ------------------ ادامه تحلیل ------------------
# استخراج ماه
df['Month'] = df['Date'].astype(str).str.split('/').str[1].astype(int)

