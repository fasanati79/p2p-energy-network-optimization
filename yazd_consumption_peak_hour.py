import pandas as pd
import itertools

# 1. خواندن میانگین مصرف ساعتی ماهانه
df = pd.read_excel("Monthly_Hourly_Mean.xlsx", index_col=0)  # ستون‌ها: H1 تا H24
df.columns = [int(c[1:]) if isinstance(c, str) and c.startswith('H') else int(c) for c in df.columns]

window = 6  # طول بازه زمانی (ساعت)

def build_blocks(row):
    candidates = []
    for start in range(1, 25 - window + 1):
        end = start + window - 1
        hours = list(range(start, end + 1))
        total = row[hours].sum()
        candidates.append({'start': start, 'end': end, 'hours': set(hours), 'total': total})
    return candidates

def select_best_4_blocks(candidates):
    best_combo = None
    max_total = -1
    # تمام ترکیب‌های 4تایی از بازه‌ها را بررسی کن
    for combo in itertools.combinations(candidates, 4):
        overlap = False
        all_hours = set()
        for blk in combo:
            if all_hours & blk['hours']:
                overlap = True
            all_hours.update(blk['hours'])
        total = sum(blk['total'] for blk in combo)
        if total > max_total:
            best_combo = combo
            max_total = total
            # اگر بدون هم‌پوشانی بود، بهترین حالت را بگیر
            if not overlap:
                break
    return best_combo

# 2. اجرای الگوریتم برای هر ماه
all_results = []
for month in df.index:
    row = df.loc[month]
    blocks = build_blocks(row)
    selected = select_best_4_blocks(blocks)
    # سطح مصرف از کم به زیاد
    selected_sorted = sorted(selected, key=lambda x: x['total'])
    levels = ['Low', 'Medium', 'High', 'Very High']
    for level, blk in zip(levels, selected_sorted):
        all_results.append({
            'Month': month,
            'StartHour': blk['start'],
            'EndHour': blk['end'],
            'Consumption': blk['total'],
            'Level': level
        })

# 3. ذخیره خروجی
result_df = pd.DataFrame(all_results)
result_df.sort_values(by=['Month', 'StartHour'], inplace=True)
result_df.to_excel("Final_4TimeBlocks_PerMonth.xlsx", index=False)
