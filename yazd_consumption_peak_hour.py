import pandas as pd

# 1. خواندن میانگین مصرف ساعتی ماهانه
df = pd.read_excel("Monthly_Hourly_Mean.xlsx", index_col=0)  # هر سطر یک ماه، ستون‌ها H1 تا H24
df.columns = [int(col[1:]) if isinstance(col, str) and col.startswith('H') else int(col) for col in df.columns]

# 2. تعریف Sliding Window و تابع بدون هم‌پوشانی
def extract_top_blocks(month_row, window_sizes=[6], top_n=4):
    results = []
    used_hours = set()
    for window in window_sizes:
        blocks = []
        for start in range(1, 25 - window + 1):
            end = start + window - 1
            hours = list(range(start, end + 1))
            total = month_row[hours].sum()
            blocks.append((start, end, total))

        # مرتب‌سازی نزولی بر اساس مجموع مصرف
        blocks_sorted = sorted(blocks, key=lambda x: -x[2])

        selected = []
        for start, end, total in blocks_sorted:
            block_range = set(range(start, end + 1))
            if block_range & used_hours:
                continue
            selected.append((start, end, total))
            used_hours.update(block_range)
            if len(selected) >= top_n:
                break

        results.extend(selected)
    return results

# 3. اجرای تابع برای هر ماه
final_blocks = []
for month in df.index:
    row = df.loc[month]
    blocks = extract_top_blocks(row, window_sizes=[6], top_n=4)
    blocks_sorted = sorted(blocks, key=lambda x: x[2])  # مرتب‌سازی صعودی برای تعیین سطح
    levels = ['Low', 'Medium', 'High', 'Very High']
    for lvl, (start, end, total) in zip(levels, blocks_sorted):
        final_blocks.append({
            'Month': month,
            'StartHour': start,
            'EndHour': end,
            'Consumption': total,
            'Level': lvl
        })

# 4. ساخت دیتافریم و ذخیره خروجی
tb_df = pd.DataFrame(final_blocks)
tb_df.sort_values(by=['Month', 'StartHour'], inplace=True)
tb_df.to_excel("TimeBlocks_ByMonth.xlsx", index=False)
print("✅ فایل TimeBlocks_ByMonth.xlsx ذخیره شد.")

