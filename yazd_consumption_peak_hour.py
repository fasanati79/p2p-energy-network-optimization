from sklearn.cluster import KMeans

# بازآرایی داده‌ها از wide به long
df_k = monthly_hourly_avg.reset_index().melt(id_vars='Month', var_name='Hour', value_name='Consumption')
df_k['Hour'] = df_k['Hour'].str.extract('H(\d+)').astype(int)

# خوشه‌بندی جداگانه برای هر ماه
def classify_kmeans(group):
    group = group.copy()
    X = group[['Consumption']].values
    kmeans = KMeans(n_clusters=4, random_state=42, n_init=10)
    group['Cluster'] = kmeans.fit_predict(X)

    # مرتب‌سازی خوشه‌ها از کم‌مصرف به پُرمصرف
    cluster_order = group.groupby('Cluster')['Consumption'].mean().sort_values().index
    level_map = {cluster: label for cluster, label in zip(cluster_order, ['Low', 'Medium', 'High', 'Very High'])}
    group['Level'] = group['Cluster'].map(level_map)

    return group.drop(columns='Cluster')

df_k_final = df_k.groupby('Month').apply(classify_kmeans).reset_index(drop=True)

# ذخیره در اکسل
df_k_final.to_excel("Hourly_Levels_KMeans.xlsx", index=False)

