import pandas as pd
import numpy as np
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import silhouette_score
import matplotlib.pyplot as plt
from geopy.distance import geodesic
from itertools import combinations

# مرحله 1: خواندن داده‌ها
df = pd.read_csv("yazd_battery_candidate_sites.csv")

# مرحله 2: انتخاب ویژگی‌ها
features_raw = df[["Latitude", "Longitude", "Grid_Proximity", "Security_Level", "Permit_Ease"]]

# مرحله 3: نرمال‌سازی ویژگی‌ها
scaler = StandardScaler()
features_scaled = scaler.fit_transform(features_raw)

# مرحله 4: تعریف وزن‌ها (اهمیت هر ویژگی)
weights = {
    "Latitude": 1.0,
    "Longitude": 1.0,
    "Grid_Proximity":1,
    "Security_Level": 1,
    "Permit_Ease": 1
}
# بردار وزن‌ها به ترتیب ستون‌های features_raw
weights_vector = np.array([weights[col] for col in features_raw.columns])

# مرحله 5: اعمال وزن‌ها روی داده‌های نرمال‌شده
features_weighted = features_scaled * weights_vector

# مرحله 6: تحلیل بهترین k با Elbow و Silhouette
K_range = range(2, 15)
inertias = []
sil_scores = []

for k in K_range:
    model = KMeans(n_clusters=k, random_state=42, n_init=10)
    labels = model.fit_predict(features_weighted)
    inertias.append(model.inertia_)
    sil_scores.append(silhouette_score(features_weighted, labels))

# رسم نمودارها
plt.figure(figsize=(12, 5))
plt.subplot(1, 2, 1)
plt.plot(K_range, inertias, 'bo-')
plt.title("Elbow Method")
plt.xlabel("K")
plt.ylabel("Inertia")
plt.grid(True)

plt.subplot(1, 2, 2)
plt.plot(K_range, sil_scores, 'go-')
plt.title("Silhouette Score")
plt.xlabel("K")
plt.ylabel("Silhouette Score")
plt.grid(True)
plt.tight_layout()
plt.show()

# مرحله 7: انتخاب بهترین k از روی سیلوئت
best_k =  K_range[np.argmax(sil_scores)]
print(f"✅ بهترین k: {best_k} با سیلوئت {max(sil_scores):.3f}")

# مرحله 8: اجرای نهایی خوشه‌بندی
final_model = KMeans(n_clusters=best_k, random_state=42, n_init=10)
df["Cluster"] = final_model.fit_predict(features_weighted)
centroids_weighted = final_model.cluster_centers_

# فقط دو ستون اول (Latitude و Longitude) را به مختصات واقعی برگردانیم
latlon_scaler = StandardScaler()
latlon_scaled = latlon_scaler.fit_transform(df[["Latitude", "Longitude"]])
centroids_latlon = latlon_scaler.inverse_transform(centroids_weighted[:, :2])

# مرحله 9: فیلتر مراکز خیلی نزدیک‌تر از threshold_km
threshold_km = 0.7  # مثلاً 700 متر
selected = list(range(len(centroids_latlon)))
removed = set()
for i, j in combinations(selected, 2):
    if i in removed or j in removed:
        continue
    dist = geodesic(centroids_latlon[i], centroids_latlon[j]).km
    if dist < threshold_km:
        removed.add(j)

final_centroids = [centroids_latlon[i] for i in selected if i not in removed]
df_centroids = pd.DataFrame(final_centroids, columns=["Latitude", "Longitude"])

# مرحله 10: رسم نهایی
plt.figure(figsize=(10, 6))
plt.scatter(df["Longitude"], df["Latitude"], c=df["Cluster"], cmap="tab10", s=40, label="Spot")
plt.scatter(df_centroids["Longitude"], df_centroids["Latitude"], c="black", s=200, marker="X", label="Final Centers")
plt.title(f"Final centers after distance filtering< {threshold_km} km")
plt.xlabel("Longitude")
plt.ylabel("Latitude")
plt.grid(True)
plt.legend()
plt.tight_layout()
plt.show()

# ذخیره خروجی
df_centroids.to_csv("final_centroids_filtered.csv", index=False)
print(f"📁 فایل final_centroids_filtered.csv با {len(df_centroids)} مرکز ذخیره شد.")

